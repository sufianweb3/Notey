/**
 * Turns drizzle-kit's SQL files into a TS module so every target (Workers,
 * Vercel, Node) can run migrations without filesystem access.
 * Run via `pnpm db:generate`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const dir = join(import.meta.dirname, '../src/server/db/migrations');
const journal = JSON.parse(readFileSync(join(dir, 'meta/_journal.json'), 'utf8')) as {
  entries: { idx: number; tag: string }[];
};

const migrations = journal.entries
  .sort((a, b) => a.idx - b.idx)
  .map((e) => {
    const sql = readFileSync(join(dir, `${e.tag}.sql`), 'utf8');
    const statements = sql
      .split('--> statement-breakpoint')
      .map((s) => s.trim())
      .filter(Boolean);
    return { tag: e.tag, statements };
  });

const out = `// Generated by scripts/bundle-migrations.ts. Do not edit.
export type Migration = { tag: string; statements: string[] };

export const migrations: Migration[] = ${JSON.stringify(migrations, null, 2)};
`;
writeFileSync(join(dir, 'index.ts'), out);
console.log(`Bundled ${migrations.length} migration(s)`);
